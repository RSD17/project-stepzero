    import argparse
    import sys

    from stepzero.graph_builder import build_graph, GraphBuildError
    from stepzero.recommendation import recommend_next

    parser = argparse.ArgumentParser(
        description="Generate, validate, and compare the synthetic Project Step Zero learner profiles."
    )
    parser.add_argument(
        "--generate", action="store_true",
        help="Regenerate the profile files in data/students from the persona definitions.",
    )
    parser.add_argument(
        "--profiles-dir", default=None,
        help="Optional path to a data/students-style directory. Defaults to the project's data/students.",
    )
    parser.add_argument(
        "--detail", action="store_true",
        help="Also print the top recommendations and strongest and weakest concepts per profile.",
    )
    args = parser.parse_args()

    try:
        curriculum = build_graph()
    except GraphBuildError as e:
        print(f"Could not build graph: {e}")
        sys.exit(1)

    target_dir = Path(args.profiles_dir) if args.profiles_dir else PROFILES_DIR

    if args.generate:
        paths = write_profile_files(curriculum, output_dir=target_dir)
        print(f"Wrote {len(paths)} profile(s) to {target_dir}:")
        for path in paths:
            print(f"  {path.name}")
        print()

    try:
        profiles = load_all_profiles(target_dir, graph=curriculum)
    except ProfileError as e:
        print(f"Could not load profiles: {e}")
        sys.exit(1)

    print("All profiles below are synthetic research personas, not observed student data.\n")
    print(format_profile_comparison(profiles, curriculum))

    if args.detail:
        for student in profiles.values():
            print()
            print(f"--> {student.name} ({student.metadata.get('persona')})")
            scored = sorted(
                student.progress.values(), key=lambda p: (-p.mastery_score, p.concept_id)
            )
            strongest = scored[:3]
            weakest = scored[-3:]
            print("   strongest:")
            for record in strongest:
                print(f"     {record.mastery_score:.2f}  {record.concept_id}")
