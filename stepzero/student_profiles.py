# Generation and loading

def write_profile_files(
    graph: nx.DiGraph,
    output_dir: str | Path = PROFILES_DIR,
    specs: list[PersonaSpec] | None = None,
) -> list[Path]:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    written = []
    for spec in specs if specs is not None else PERSONAS:
        student = build_profile(spec, graph)
        data = student.to_dict()

        # Generated files are validated before they are written, never after.
        validate_profile(data, graph=graph, raise_on_error=True)

        path = output_dir / f"{spec.student_id}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
        written.append(path)
    return written


def load_profile(
    path: str | Path, graph: nx.DiGraph | None = None, validate: bool = True
) -> Student:
    path = Path(path)
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if validate:
        try:
            validate_profile(data, graph=graph, raise_on_error=True)
        except ProfileValidationError as e:
            raise ProfileError(f"{path} is not a usable profile:\n{e}") from e

    return Student.from_dict(data)


def load_all_profiles(
    directory: str | Path = PROFILES_DIR,
    graph: nx.DiGraph | None = None,
    validate: bool = True,
) -> dict[str, Student]:
    directory = Path(directory)
    files = sorted(glob(str(directory / "*.json")))
    if not files:
        raise ProfileError(f"No student profile files found in {directory}")

    students: dict[str, Student] = {}
    for file_path in files:
        student = load_profile(file_path, graph=graph, validate=validate)
        if student.student_id in students:
            raise ProfileError(
                f"Duplicate student_id '{student.student_id}' found in {file_path}."
            )
        students[student.student_id] = student
    return students


# Human-readable reporting

def profile_overview(student: Student, graph: nx.DiGraph) -> dict:
    completed = student.completed_concepts()
    eligible = student.eligible_concepts(graph)
    return {
        "student_id": student.student_id,
        "name": student.name,
        "persona": student.metadata.get("persona", "unknown"),
        "touched": len(student.progress),
        "mastered": len(completed),
        "average_mastery": student.average_mastery(),
        "study_hours": student.total_study_hours(),
        "eligible": len(eligible),
        "events": len(student.history),
    }


def format_profile_comparison(students: dict[str, Student], graph: nx.DiGraph) -> str:
    from stepzero.recommendation import recommend_next

    header = (
        f"{'Persona':<16}{'Touched':>8}{'Mastered':>9}{'AvgMast':>9}"
        f"{'Hours':>9}{'Eligible':>9}  Top recommendation"
    )
    lines = [header, "=" * len(header)]

    for student in students.values():
        overview = profile_overview(student, graph)
        recommendations = recommend_next(graph, student, top_n=1)
        if recommendations:
            top = recommendations[0]
            label = graph.nodes[top.concept_id].get("name", top.concept_id)
            top_text = f"{label} ({top.score:.3f})"
        else:
            top_text = "none, curriculum exhausted"

        lines.append(
            f"{overview['persona']:<16}{overview['touched']:>8}{overview['mastered']:>9}"
            f"{overview['average_mastery']:>9.3f}{overview['study_hours']:>9.1f}"
            f"{overview['eligible']:>9}  {top_text}"
        )
    return "\n".join(lines)


