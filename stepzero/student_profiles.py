PROFILES_DIR = Path(__file__).resolve().parent.parent / "data" / "students"

PROFILE_GENERATOR_VERSION = "1.0"

# Fixed anchor date so regenerating a profile always produces identical timestamps.
PROFILE_EPOCH = datetime(2025, 1, 6, 9, 0, 0)

# Crammed concepts land in a narrow band, a shallow pass rather than a failure.
CRAMMED_MASTERY_FLOOR = 0.52
CRAMMED_MASTERY_CEILING = 0.62

DISCLAIMER = (
    "Synthetic research persona generated by stepzero.student_profiles. This is designed "
    "test material, not observed data, and it is not derived from or calibrated against any "
    "real student. It exists to give Project Step Zero v1.0 controlled, reproducible inputs "
    "for recommendation, simulation, and evaluation experiments, and is expected to be "
    "replaced or calibrated once primary research data is collected."
)


class ProfileError(Exception):
    pass


@dataclass(frozen=True)
class PersonaSpec:
    student_id: str
    name: str
    persona: str
    description: str
    design_notes: tuple[str, ...]

    # Coverage, which concepts this learner has ever opened
    subject_reach: dict[str, int]
    subject_coverage: dict[str, float]
    required: tuple[str, ...] = ()

    # Mastery model, applied to every touched concept
    base_mastery: float = 0.7
    depth_decay: float = 0.04
    category_modifiers: dict[str, float] = field(default_factory=dict)
    jitter: float = 0.10
    mastery_threshold: float = 0.75

    # Effort model
    attempts_base: float = 1.5
    attempts_per_missing_mastery: float = 3.0
    hours_multiplier: float = 1.0

    # Self assessment bias, positive means the learner overrates themselves
    confidence_bias: float = 0.0

    # Deliberate, documented departures from the smooth model
    gaps: dict[str, float] = field(default_factory=dict)
    bright_spots: dict[str, float] = field(default_factory=dict)
    forgotten: tuple[str, ...] = ()
    crammed: tuple[str, ...] = ()

    # Study calendar, in weeks relative to PROFILE_EPOCH
    study_start_week: int = 0
    study_weeks: int = 20


def _stable_unit(*parts: str) -> float:
    # Deterministic value in [0, 1), stable across runs, processes, and platforms.
    key = "|".join(parts).encode("utf-8")
    return (zlib.crc32(key) % 100_000) / 100_000.0


def _clamp(value: float, lo: float = 0.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, value))


def _category_of(graph: nx.DiGraph, concept_id: str) -> str:
    return graph.nodes[concept_id].get("category", "uncategorized")


def _subject_of(concept_id: str) -> str:
    return concept_id.split(".", 1)[0]


def _forced_concepts(spec: PersonaSpec, graph: nx.DiGraph) -> set[str]:
    # Concepts the persona definition pins in place regardless of the coverage draw.
    forced = set(spec.crammed) | set(spec.bright_spots) | set(spec.gaps) | set(spec.forgotten)
    for concept_id in spec.required:
        if concept_id not in graph.nodes:
            raise ProfileError(
                f"Persona '{spec.student_id}' requires '{concept_id}', which is not in the graph."
            )
        forced.add(concept_id)
        forced |= nx.ancestors(graph, concept_id)
    return forced


def _select_touched(
    spec: PersonaSpec, graph: nx.DiGraph, depths: dict[str, int], order: list[str]
) -> list[str]:
    # Walking topological order keeps study sequence prerequisite-aware by construction.
    forced = _forced_concepts(spec, graph)
    touched: list[str] = []
    touched_set: set[str] = set()

    for concept_id in order:
        if concept_id in forced:
            touched.append(concept_id)
            touched_set.add(concept_id)
            continue

        subject = _subject_of(concept_id)
        reach = spec.subject_reach.get(subject)
        if reach is None or depths[concept_id] > reach:
            continue

        # A learner normally opens a concept only after opening its prerequisites.
        if not set(graph.predecessors(concept_id)).issubset(touched_set):
            continue

        # The coverage draw only bites near the persona's reach, never at foundations.
        coverage = spec.subject_coverage.get(subject, 1.0)
        depth_fraction = depths[concept_id] / max(1, reach)
        effective_coverage = coverage + (1 - coverage) * (1 - depth_fraction)

        if _stable_unit(spec.student_id, concept_id, "coverage") < effective_coverage:
            touched.append(concept_id)
            touched_set.add(concept_id)

    return touched


def _target_mastery(
    spec: PersonaSpec, graph: nx.DiGraph, concept_id: str, depths: dict[str, int]
) -> float:
    if concept_id in spec.gaps:
        return _clamp(spec.gaps[concept_id])
    if concept_id in spec.bright_spots:
        return _clamp(spec.bright_spots[concept_id])

    value = spec.base_mastery
    value -= spec.depth_decay * depths[concept_id]
    value += spec.category_modifiers.get(_category_of(graph, concept_id), 0.0)
    value += (_stable_unit(spec.student_id, concept_id, "mastery") - 0.5) * spec.jitter

    # Knowledge that was mastered long ago and never revisited has decayed.
    if concept_id in spec.forgotten:
        value *= 0.5
    # Crammed material was drilled to a shallow pass, neither solid nor failed.
    if concept_id in spec.crammed:
        value = _clamp(value, CRAMMED_MASTERY_FLOOR, CRAMMED_MASTERY_CEILING)

    return _clamp(value)


def _attempt_count(spec: PersonaSpec, concept_id: str, mastery: float) -> int:
    missing = 1.0 - mastery
    raw = spec.attempts_base + spec.attempts_per_missing_mastery * missing
    raw += (_stable_unit(spec.student_id, concept_id, "attempts") - 0.5) * 1.2
    return max(1, round(raw))


def _attempt_scores(spec: PersonaSpec, concept_id: str, mastery: float, attempts: int) -> list[float]:
    # Earlier attempts sit below the final level so each concept shows a learning curve.
    scores = []
    for i in range(attempts):
        ramp = 0.22 * (attempts - 1 - i) / (attempts - 1) if attempts > 1 else 0.0
        noise = (_stable_unit(spec.student_id, concept_id, f"attempt{i}") - 0.5) * 0.08
        scores.append(round(_clamp(mastery - ramp + noise), 3))
    return scores


def _build_metadata(spec: PersonaSpec) -> dict:
    return {
        "synthetic": True,
        "persona": spec.persona,
        "description": spec.description,
        "disclaimer": DISCLAIMER,
        "generator_version": PROFILE_GENERATOR_VERSION,
        "design_notes": list(spec.design_notes),
    }


def build_profile(spec: PersonaSpec, graph: nx.DiGraph) -> Student:
    # Records are built directly because start_concept and record_attempt stamp datetime.now().
    depths = concept_depths(graph)
    if depths is None:
        raise ProfileError("Cannot build profiles against a graph that contains a cycle.")

    order = topological_sort(graph).order
    touched = _select_touched(spec, graph, depths, order)

    created_at = PROFILE_EPOCH + timedelta(days=spec.study_start_week * 7 - 3)
    student = Student(
        student_id=spec.student_id,
        name=spec.name,
        created_at=created_at,
        metadata=_build_metadata(spec),
    )

    span_days = spec.study_weeks * 7
    start_day = spec.study_start_week * 7

    for index, concept_id in enumerate(touched):
        mastery = round(_target_mastery(spec, graph, concept_id, depths), 4)
        attempts = _attempt_count(spec, concept_id, mastery)
        is_mastered = (
            mastery >= spec.mastery_threshold
            or concept_id in spec.forgotten
            or concept_id in spec.crammed
        )

        estimated_hours = graph.nodes[concept_id].get("estimated_study_hours", 3.0)
        effort_spread = 0.85 + 0.3 * _stable_unit(spec.student_id, concept_id, "hours")
        hours = estimated_hours * spec.hours_multiplier * (1 + 0.35 * (attempts - 1)) * effort_spread

        confidence = _clamp(
            mastery
            + spec.confidence_bias
            + (_stable_unit(spec.student_id, concept_id, "confidence") - 0.5) * 0.08
        )

        position = index / (len(touched) - 1) if len(touched) > 1 else 0.0
        day_offset = start_day + position * span_days
        hour_offset = int(_stable_unit(spec.student_id, concept_id, "hour") * 10)
        first_studied = PROFILE_EPOCH + timedelta(days=round(day_offset), hours=hour_offset)

        review_gap = attempts * 3 + int(_stable_unit(spec.student_id, concept_id, "gap") * 5)
        last_reviewed = first_studied + timedelta(days=review_gap)

        student.progress[concept_id] = ConceptProgress(
            concept_id=concept_id,
            status=MasteryStatus.MASTERED if is_mastered else MasteryStatus.IN_PROGRESS,
            mastery_score=mastery,
            attempts=attempts,
            time_spent_hours=round(hours, 2),
            self_rated_confidence=round(confidence, 2),
            first_studied_at=first_studied,
            last_reviewed_at=last_reviewed,
            completed_at=last_reviewed if is_mastered else None,
        )

        student.history.append(
            LearningEvent(
                concept_id=concept_id,
                event_type=LearningEventType.STARTED,
                timestamp=first_studied,
                details={},
            )
        )

        scores = _attempt_scores(spec, concept_id, mastery, attempts)
        for i, score in enumerate(scores):
            fraction = (i + 1) / attempts
            student.history.append(
                LearningEvent(
                    concept_id=concept_id,
                    event_type=LearningEventType.ATTEMPTED,
                    timestamp=first_studied + (last_reviewed - first_studied) * fraction,
                    details={
                        "score": score,
                        "time_spent_hours": round(hours / attempts, 2),
                        "self_rated_confidence": round(confidence, 2),
                    },
                )
            )

        if is_mastered:
            student.history.append(
                LearningEvent(
                    concept_id=concept_id,
                    event_type=LearningEventType.MASTERED,
                    timestamp=last_reviewed,
                    details={"mastery_score": mastery},
                )
            )

    student.history.sort(key=lambda e: e.timestamp)
    return student


