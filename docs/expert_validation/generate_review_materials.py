"""Generate expert-review materials from the frozen repository data. Read-only on all inputs."""

import hashlib
import json
from collections import defaultdict
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SUBJECTS = REPO / "data" / "subjects"
OUT = Path(__file__).resolve().parent
TRAJECTORY = REPO / "experiments" / "results" / "trajectory_sensitivity.json"

SUBJECT_ORDER = ["mathematics", "physics", "chemistry", "biology", "computer_science"]
DISPLAY = {"mathematics": "Mathematics", "physics": "Physics", "chemistry": "Chemistry",
           "biology": "Biology", "computer_science": "Computer Science"}


def load():
    concepts, edges = {}, []
    for name in SUBJECT_ORDER:
        d = json.loads((SUBJECTS / f"{name}.json").read_text(encoding="utf-8"))
        for c in d["concepts"]:
            concepts[c["id"]] = c
        for e in d["edges"]:
            edges.append({"source": e["source"], "target": e["target"], "listed_in": name})
    return concepts, edges


def priority_rates():
    """Top-1 change rate per edge from the completed trajectory experiment, if available."""
    if not TRAJECTORY.exists():
        return {}
    d = json.loads(TRAJECTORY.read_text(encoding="utf-8"))
    agg = defaultdict(lambda: {"states": 0, "changes": 0})
    for r in d["rows"]:
        key = r["perturbation"].split(":", 1)[1]
        agg[key]["states"] += 1
        agg[key]["changes"] += (not r["top1_agreement"])
    return {k: v["changes"] / v["states"] for k, v in agg.items() if v["states"]}


def short(cid, concepts):
    c = concepts.get(cid)
    return c["name"] if c else cid.split(".")[-1].replace("_", " ").title()


def write_subject(name, concepts, edges, rates):
    subject_concepts = [c for c in concepts.values() if c["subject"] == name]
    subject_concepts.sort(key=lambda c: (c["category"], c["name"]))
    incoming = [e for e in edges if e["target"].split(".")[0] == name]
    outgoing_cross = [e for e in edges
                      if e["source"].split(".")[0] == name
                      and e["target"].split(".")[0] != name]

    L = []
    L.append(f"# Expert Review Sheet: {DISPLAY[name]}")
    L.append("")
    L.append(f"Generated {date.today().isoformat()} from `data/subjects/{name}.json`. "
             "Do not edit this file by hand; it is regenerated from the repository data.")
    L.append("")
    L.append(f"**{len(subject_concepts)} concepts, {len(incoming)} prerequisite relationships "
             f"pointing into this subject.**")
    L.append("")
    L.append("Read each relationship as: **source is a prerequisite for target**, that is, a "
             "learner should normally study the source before the target.")
    L.append("")

    L.append("## 1. Concepts in this subject")
    L.append("")
    L.append("| Concept ID | Name | Category | Level | Difficulty (1-5) | Est. hours |")
    L.append("|---|---|---|---|---|---|")
    for c in subject_concepts:
        L.append(f"| `{c['id']}` | {c['name']} | {c['category']} | {c['educational_level']} "
                 f"| {c['difficulty']} | {c['estimated_study_hours']} |")
    L.append("")

    L.append("### Concept descriptions")
    L.append("")
    for c in subject_concepts:
        L.append(f"**{c['name']}** (`{c['id']}`)  ")
        L.append(f"{c['description']}  ")
        if c.get("learning_objectives"):
            L.append(f"*Objectives:* " + "; ".join(c["learning_objectives"]))
        L.append("")

    L.append("## 2. Prerequisite relationships to review")
    L.append("")
    L.append("`WITHIN` means both concepts are in this subject. `CROSS-SUBJECT` means the "
             "prerequisite comes from another subject; those are listed again in section 3.")
    L.append("")
    L.append("Priority is the proportion of tested learner states at which removing or reversing "
             "this relationship changed the top recommendation, from the computational "
             "sensitivity analysis. **High priority means the relationship matters most to the "
             "software's behaviour. It says nothing about whether the relationship is correct.**")
    L.append("")
    L.append("| # | Prerequisite (source) | Leads to (target) | Scope | Priority |")
    L.append("|---|---|---|---|---|")
    ordered = sorted(incoming, key=lambda e: (-rates.get(f"{e['source']}->{e['target']}", 0.0),
                                              e["target"]))
    for i, e in enumerate(ordered, 1):
        cross = e["source"].split(".")[0] != name
        scope = "CROSS-SUBJECT" if cross else "WITHIN"
        r = rates.get(f"{e['source']}->{e['target']}")
        band = "-" if r is None else ("high" if r >= 0.4 else "medium" if r >= 0.1 else "low")
        src_lbl = short(e["source"], concepts)
        tgt_lbl = short(e["target"], concepts)
        src_pre = "" if not cross else f"[{e['source'].split('.')[0]}] "
        L.append(f"| {i} | {src_pre}{src_lbl}<br>`{e['source']}` | {tgt_lbl}<br>`{e['target']}` "
                 f"| {scope} | {band}{'' if r is None else f' ({r:.2f})'} |")
    L.append("")

    L.append("## 3. Cross-subject prerequisites")
    L.append("")
    cross_in = [e for e in incoming if e["source"].split(".")[0] != name]
    if cross_in:
        L.append(f"These {len(cross_in)} relationships claim that a concept from another subject "
                 "should be studied before a concept in this one. They may need a reviewer from "
                 "each subject.")
        L.append("")
        L.append("| Prerequisite subject | Prerequisite | Leads to (in this subject) |")
        L.append("|---|---|---|")
        for e in cross_in:
            L.append(f"| {DISPLAY.get(e['source'].split('.')[0], e['source'].split('.')[0])} "
                     f"| {short(e['source'], concepts)}<br>`{e['source']}` "
                     f"| {short(e['target'], concepts)}<br>`{e['target']}` |")
    else:
        L.append("None: every prerequisite for this subject comes from within the subject.")
    L.append("")
    if outgoing_cross:
        L.append(f"This subject also supplies {len(outgoing_cross)} prerequisites to other "
                 "subjects:")
        L.append("")
        L.append("| From (this subject) | Leads to | In subject |")
        L.append("|---|---|---|")
        for e in outgoing_cross:
            L.append(f"| {short(e['source'], concepts)}<br>`{e['source']}` "
                     f"| {short(e['target'], concepts)}<br>`{e['target']}` "
                     f"| {DISPLAY.get(e['target'].split('.')[0], '')} |")
        L.append("")

    L.append("## 4. Concepts with no listed prerequisites")
    L.append("")
    has_pre = {e["target"] for e in incoming}
    roots = [c for c in subject_concepts if c["id"] not in has_pre]
    L.append(f"{len(roots)} of {len(subject_concepts)} concepts have no prerequisite recorded. "
             "Please note any that you believe should have one.")
    L.append("")
    for c in roots:
        L.append(f"- {c['name']} (`{c['id']}`), {c['educational_level']}")
    L.append("")
    return "\n".join(L) + "\n"


def main():
    concepts, edges = load()
    rates = priority_rates()
    OUT.mkdir(parents=True, exist_ok=True)

    written = []
    for name in SUBJECT_ORDER:
        text = write_subject(name, concepts, edges, rates)
        p = OUT / f"review_{name}.md"
        p.write_text(text, encoding="utf-8")
        written.append(p)

    # Provenance tying each sheet to an exact graph state, in the repo's sorted-path hash order
    fp = hashlib.sha256()
    for p in sorted(SUBJECTS / f"{n}.json" for n in SUBJECT_ORDER):
        fp.update(p.read_bytes())
    structural = None
    if TRAJECTORY.exists():
        structural = json.loads(TRAJECTORY.read_text(encoding="utf-8"))["provenance"]
    provenance = {
        "generated": date.today().isoformat(),
        "subject_data_fingerprint": fp.hexdigest()[:16],
        "graph_fingerprint": structural["graph_fingerprint"] if structural else None,
        "matches_experiment_outputs": bool(
            structural and structural["subject_data_fingerprint"] == fp.hexdigest()[:16]),
        "per_file_sha256": {f"{n}.json": hashlib.sha256(
            (SUBJECTS / f"{n}.json").read_bytes()).hexdigest()[:16] for n in SUBJECT_ORDER},
        "concepts": len(concepts),
        "edges": len(edges),
        "cross_subject_edges": sum(1 for e in edges
                                   if e["source"].split(".")[0] != e["target"].split(".")[0]),
        "priority_source": ("experiments/results/trajectory_sensitivity.json"
                            if rates else "unavailable"),
        "files": [p.name for p in written],
    }
    (OUT / "provenance.json").write_text(json.dumps(provenance, indent=2), encoding="utf-8")
    for p in written:
        print(f"  wrote {p.relative_to(REPO)}")
    print(f"  wrote {(OUT / 'provenance.json').relative_to(REPO)}")
    print(f"  concepts {provenance['concepts']}, edges {provenance['edges']}, "
          f"cross-subject {provenance['cross_subject_edges']}, "
          f"fingerprint {provenance['subject_data_fingerprint']}")


if __name__ == "__main__":
    main()
